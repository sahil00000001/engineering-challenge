/*
  Captures real footage of the live showcase for the films.

    node source/capture-footage.cjs [url]

  Writes source/footage/:
    site.png          full page, every "Checks" panel closed
    site-checks.png   full page, every "Checks" panel open
    site-layout.js    window.SITE = { width, height, scale, boxes: {...} } — CSS-px boxes
                      of the elements the films zoom into (loaded as a script, because
                      scenes run over file:// where fetch() of local JSON is blocked)

  Footage is a Chromium screenshot of the deployed page, not a mock-up.
*/
const fs = require('fs');
const path = require('path');
const { chromium } = require('playwright');

const URL_ = process.argv[2] || 'https://task-7-insight-template.vercel.app/';
const OUT = path.join(__dirname, 'footage');
const WIDTH = 1440;
const SCALE = 1.5;

(async () => {
  fs.mkdirSync(OUT, { recursive: true });
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: WIDTH, height: 900 }, deviceScaleFactor: SCALE });
  await page.goto(URL_, { waitUntil: 'networkidle' });
  await page.evaluate(() => document.fonts.ready);

  await page.screenshot({ path: path.join(OUT, 'site.png'), fullPage: true });

  const layout = await page.evaluate(() => {
    const box = (el) => {
      const r = el.getBoundingClientRect();
      return { x: Math.round(r.left + scrollX), y: Math.round(r.top + scrollY), w: Math.round(r.width), h: Math.round(r.height) };
    };
    const boxes = {
      header: box(document.querySelector('.site-header')),
      hero: box(document.querySelector('.hero')),
      featured: box(document.querySelector('.featured')),
      pipeline: box(document.querySelector('.pipeline')),
      gallery: box(document.querySelector('.gallery')),
    };
    for (const card of document.querySelectorAll('.example')) {
      const name = card.querySelector('.example__name').textContent;
      boxes['card:' + name] = box(card);
      boxes['summary:' + name] = box(card.querySelector('summary'));
      boxes['media:' + name] = box(card.querySelector('.example__media'));
    }
    return { width: document.documentElement.scrollWidth, height: document.documentElement.scrollHeight, boxes };
  });

  await page.evaluate(() => document.querySelectorAll('details').forEach((d) => (d.open = true)));
  const openLayout = await page.evaluate(() => {
    const out = {};
    for (const card of document.querySelectorAll('.example')) {
      const r = card.getBoundingClientRect();
      out['card:' + card.querySelector('.example__name').textContent] = {
        x: Math.round(r.left + scrollX), y: Math.round(r.top + scrollY), w: Math.round(r.width), h: Math.round(r.height),
      };
    }
    return { height: document.documentElement.scrollHeight, boxes: out };
  });
  // Each card on its own, with only its own "Checks" panel open, so a film can show
  // one real click expanding one card without the rest of the page jumping.
  const cards = await page.$$('.example');
  for (const card of cards) {
    const name = await card.$eval('.example__name', (n) => n.textContent);
    await page.evaluate(() => document.querySelectorAll('details').forEach((d) => (d.open = false)));
    await card.$eval('details', (d) => (d.open = true));
    await card.screenshot({ path: path.join(OUT, `card-${name}-open.png`) });
  }

  // The live report.json files, exactly as Chromium shows them when opened from the site.
  const reports = await browser.newPage({ viewport: { width: 1100, height: 980 }, deviceScaleFactor: SCALE });
  for (const fixture of ['long-body', 'changed-after-approval', 'missing-source-note']) {
    await reports.goto(new URL(`src/task-7_sahil-vashisht/examples/${fixture}/report.json`, URL_).href, { waitUntil: 'networkidle' });
    await reports.screenshot({ path: path.join(OUT, `report-${fixture}.png`) });
  }
  await browser.close();

  const SITE = { url: URL_, width: layout.width, height: layout.height, scale: SCALE, boxes: layout.boxes, open: openLayout };
  fs.writeFileSync(path.join(OUT, 'site-layout.js'), '/* generated by capture-footage.cjs */\nwindow.SITE = ' + JSON.stringify(SITE, null, 2) + ';\n');
  console.log('captured', URL_, `${layout.width}x${layout.height} css px @${SCALE}x`, Object.keys(layout.boxes).length, 'boxes');
})();
